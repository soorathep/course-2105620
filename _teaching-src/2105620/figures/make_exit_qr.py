"""Regenerate course exit-ticket QR images and weekly Quarto closing slides.

Run with the absolute research interpreter from any directory. Prompts are read
from ../exit-prompts.json, which is also used by the browser form.
"""
from __future__ import annotations

import json
import os
from pathlib import Path
import re
import sys

COURSE_ROOT = Path(__file__).resolve().parents[1]
CANONICAL_FORM = (
    "https://soorathep.github.io/course-2105620/teaching/2105620/exit.html"
)
CLOSING_IDS = {
    1: "section-5",
    2: "section-8",
    3: "section-6",
    4: "section-4",
    5: "section-2",
    6: "section-3",
    8: "how-was-today",
    9: "how-was-today",
    10: "how-was-today",
}

# Keep optional Matplotlib cache writes within the project when importing the
# lab palette. QR codes contain no fonts or personal data.
os.environ.setdefault("MPLCONFIGDIR", str(COURSE_ROOT / ".build" / "matplotlib"))
sys.path.insert(0, str(COURSE_ROOT / "files"))
import skh_palette as skh  # noqa: E402
import qrcode  # noqa: E402


def closing_slide(week: int, prompt: str) -> str:
    """Keep the existing published slide fragment IDs and course typography."""
    mode = (
        "Select **On my own** for the recorded session.\n\n"
        if week == 4 else ""
    )
    return f'''<!-- Generated by figures/make_exit_qr.py from exit-prompts.json. -->

## Exit ticket and feedback {{#{CLOSING_IDS[week]} .dark background-color="#1C242B"}}

::: {{.kicker}}
Week {week} · 2–3 minutes
:::

:::: {{.columns}}
::: {{.column width="64%"}}
::: {{.lede}}
{prompt}
:::

::: {{.small}}
{mode}Answer the question, then give short feedback.

Do not include names or student IDs.

Wait for **"Response received."**
:::
:::
::: {{.column width="36%"}}
::: {{.qr-card}}
![](assets/exit-ticket/exit-qr-s{week:02d}.png){{fig-alt="QR code for the Week {week} exit ticket and feedback form"}}
:::

::: {{.flag}}
[Open the Week {week} form](exit.html?s={week}){{target="_blank" rel="noopener"}}
:::
:::
::::

::: {{.notes}}
Allow 2–3 minutes for the exit-ticket answer and short feedback. Keep the
question visible while students respond. Ask students to omit names, student
IDs and other personal details, and wait for "Response received." before
closing the form. {'For the recorded Week 4 session, select "On my own".' if week == 4 else 'Select the study mode that matches the session.'}
Review unclear points before planning the next session.
:::
'''


def main() -> None:
    prompts = json.loads((COURSE_ROOT / "exit-prompts.json").read_text())
    expected = {str(n) for n in range(1, 15)}
    if set(prompts) != expected:
        raise ValueError("exit-prompts.json must contain exactly sessions 1–14")
    if not all(isinstance(p, str) and p.strip() for p in prompts.values()):
        raise ValueError("Every session must have a nonempty text prompt")
    # The form needs no runtime JSON request, including when opened offline.
    # Keep its embedded data and the generated slide questions synchronized.
    form_path = COURSE_ROOT / "exit.html"
    form = form_path.read_text(encoding="utf-8")
    encoded = json.dumps(prompts, ensure_ascii=False, indent=2)
    encoded = encoded.replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")
    form, count = re.subn(
        r'(<script id="exit-prompts" type="application/json">).*?(</script>)',
        lambda match: match[1] + "\n" + encoded + "\n" + match[2],
        form,
        flags=re.S,
    )
    if count != 1:
        raise ValueError("The form must have exactly one embedded exit-prompts block")
    form_path.write_text(form, encoding="utf-8")
    skh.use()
    out_dir = COURSE_ROOT / "assets" / "exit-ticket"
    out_dir.mkdir(parents=True, exist_ok=True)
    for week in range(1, 15):
        code = qrcode.QRCode(
            error_correction=qrcode.constants.ERROR_CORRECT_M,
            box_size=32,
            border=4,
        )
        code.add_data(f"{CANONICAL_FORM}?s={week}")
        code.make(fit=True)
        img = code.make_image(fill_color=skh.C["graphite"], back_color="white")
        img.save(out_dir / f"exit-qr-s{week:02d}.png", dpi=(600, 600))
        if week in CLOSING_IDS:
            (COURSE_ROOT / f"_exit-w{week:02d}.qmd").write_text(
                closing_slide(week, prompts[str(week)]), encoding="utf-8"
            )
    print(f"Generated 14 QR images at 600 dpi and {len(CLOSING_IDS)} closing includes.")


if __name__ == "__main__":
    main()
